// Task: move the CMS data into real Astro content collections.
//
// Reads reference/webflow/items/*.json (raw Webflow Data API dump) and
// reference/webflow/fields/*.json (the field schema for each collection), and:
//
//   1. Emits one JSON file per CMS item under src/content/<collection>/<id>.json,
//      containing the item VERBATIM (same shape reference/webflow/items/*.json
//      already uses: id, cmsLocaleId, lastPublished, lastUpdated, createdOn,
//      isArchived, isDraft, fieldData). No lossy conversion of any kind -- in
//      particular RichText fields stay raw Webflow HTML, never Markdown, so the
//      design (which depends on exact tags/classes) survives untouched.
//   2. Writes src/content.config.ts: one defineCollection() per collection, each
//      with a zod schema derived from the field's declared Webflow type. Nullability
//      per field is not guessed -- it's measured against every item in the dump, so
//      the schema is guaranteed to validate all 1,590 items, not just a sample.
//
// Re-run this any time the reference/webflow dump is refreshed:
//   node tools/generate-content-collections.mjs
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const ITEMS_DIR = 'reference/webflow/items';
const FIELDS_DIR = 'reference/webflow/fields';
const CONTENT_DIR = 'src/content';
const CONFIG_PATH = 'src/content.config.ts';

const collectionSlugs = readdirSync(ITEMS_DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort();

// Webflow field type -> zod expression, before nullability is applied.
const BASE_ZOD = {
  PlainText: 'z.string()',
  RichText: 'z.string()',
  Number: 'z.number()',
  Switch: 'z.boolean()',
  DateTime: 'z.string()', // ISO datetime string, kept raw (not coerced to Date) so it
                           // round-trips byte-for-byte through the equivalence check.
  Option: 'z.string()',   // the option's id, same as Reference; display name is resolved
                           // elsewhere (see optionName() in src/lib/render-detail.mjs)
  Reference: 'z.string()',
  MultiReference: 'z.array(z.string())',
  Image: "z.object({ fileId: z.string(), url: z.string(), alt: z.string().nullable() })",
  Link: 'z.string()',
  Color: 'z.string()',
  VideoLink: 'z.string()', // never populated in the current dump (see generator report)
                            // but the field type allows a URL, so the schema does too.
};

function toIdent(slug) {
  const camel = slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `_${camel}` : camel;
}

// Recursively collect every JS "kind" a value can take, to measure nullability.
function kindsOf(fieldType, value, into) {
  if (value === null || value === undefined) { into.add('null'); return; }
  into.add('present');
}

let report = [];
let configParts = [
  `// @generated by tools/generate-content-collections.mjs -- edits will be lost.\n`,
  `//\n`,
  `// One collection per Webflow CMS collection in reference/webflow/items/. Every\n`,
  `// entry is the RAW Webflow item (id, cmsLocaleId, lastPublished, lastUpdated,\n`,
  `// createdOn, isArchived, isDraft, fieldData) -- no shape change, no lossy\n`,
  `// conversion. RichText fields keep their original Webflow HTML verbatim: the\n`,
  `// site's design depends on exact tags/classes, so Markdown (which would drop or\n`,
  `// normalise markup) is never used for CMS body content. See src/lib/content.ts\n`,
  `// for the read side (getCollection()-backed equivalents of src/lib/detail-data.mjs).\n`,
  `import { defineCollection, z } from 'astro:content';\n`,
  `import { glob } from 'astro/loaders';\n\n`,
];

const collectionVarNames = [];

for (const slug of collectionSlugs) {
  const itemsPath = join(ITEMS_DIR, `${slug}.json`);
  const fieldsPath = join(FIELDS_DIR, `${slug}.json`);
  const items = JSON.parse(readFileSync(itemsPath, 'utf8'));
  const fieldDef = existsSync(fieldsPath) ? JSON.parse(readFileSync(fieldsPath, 'utf8')) : { fields: [] };

  // Measure, per field, whether null/undefined ever occurs across every item in
  // this collection -- decides `.nullable()` empirically rather than by guessing
  // from Webflow's isRequired flag (which does not reliably predict actual data).
  const fieldKinds = new Map(); // field slug -> Set<'null'|'present'>
  for (const f of fieldDef.fields ?? []) fieldKinds.set(f.slug, new Set());
  let lastPublishedNullable = false;
  for (const it of items) {
    if (it.lastPublished === null) lastPublishedNullable = true;
    for (const f of fieldDef.fields ?? []) {
      kindsOf(f.type, it.fieldData?.[f.slug], fieldKinds.get(f.slug));
    }
  }

  const varName = toIdent(slug);
  collectionVarNames.push([slug, varName]);

  const fieldLines = (fieldDef.fields ?? []).map((f) => {
    const base = BASE_ZOD[f.type];
    if (!base) throw new Error(`Unhandled Webflow field type "${f.type}" in collection "${slug}" field "${f.slug}"`);
    const kinds = fieldKinds.get(f.slug);
    const nullable = kinds.has('null');
    const expr = nullable ? `${base}.nullable()` : base;
    return `      ${JSON.stringify(f.slug)}: ${expr}, // ${f.type}`;
  });

  configParts.push(
    `const ${varName} = defineCollection({\n`,
    `  loader: glob({ pattern: '**/*.json', base: './src/content/${slug}', generateId: ({ data }) => data.id }),\n`,
    `  schema: z.object({\n`,
    `    id: z.string(),\n`,
    `    cmsLocaleId: z.string(),\n`,
    `    lastPublished: ${lastPublishedNullable ? 'z.string().nullable()' : 'z.string()'},\n`,
    `    lastUpdated: z.string(),\n`,
    `    createdOn: z.string(),\n`,
    `    isArchived: z.boolean(),\n`,
    `    isDraft: z.boolean(),\n`,
    `    fieldData: z.object({\n`,
    ...fieldLines.map((l) => l + '\n'),
    `    }),\n`,
    `  }),\n`,
    `});\n\n`,
  );

  report.push({ slug, itemCount: items.length, fieldCount: (fieldDef.fields ?? []).length });

  // Emit one JSON file per item, verbatim.
  const dir = join(CONTENT_DIR, slug);
  if (existsSync(dir)) rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const it of items) {
    writeFileSync(join(dir, `${it.id}.json`), JSON.stringify(it, null, 1) + '\n');
  }
}

configParts.push(`export const collections = {\n`);
for (const [slug, varName] of collectionVarNames) {
  configParts.push(`  ${JSON.stringify(slug)}: ${varName},\n`);
}
configParts.push(`};\n`);

writeFileSync(CONFIG_PATH, configParts.join(''));

console.log(`Wrote ${CONFIG_PATH} with ${collectionSlugs.length} collections.`);
for (const r of report) console.log(`  ${r.slug}: ${r.itemCount} items, ${r.fieldCount} fields`);
console.log(`Total items: ${report.reduce((a, r) => a + r.itemCount, 0)}`);
