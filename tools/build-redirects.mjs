// Phase 2/4: emit public/_redirects for Cloudflare.
// Limits: 2,000 static rules, 100 dynamic (splat/placeholder) rules.
import { readFileSync, writeFileSync } from 'node:fs';

const assetMap = JSON.parse(readFileSync('reference/asset-map.json', 'utf8'));
const lines = ['# Generated by tools/build-redirects.mjs -- do not edit by hand.',
  '# Source: reference/redirects-discovered.tsv (probed from live).',
  '# INCOMPLETE: Webflow exposes no redirect API. The full 301 table must be exported',
  '# by hand from Designer -> Site settings -> Publishing and merged into the source file.',
  ''];

let dynamic = 0, statics = 0;
for (const raw of readFileSync('reference/redirects-discovered.tsv', 'utf8').split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const [from, status, to] = line.split('\t').map(s => s?.trim());
  if (!from || !to) continue;

  let target = to;
  if (to.startsWith('WEBFLOW_PDF:')) {
    // These pointed at Webflow-hosted PDFs that 404 after cutover -- repoint locally.
    const name = to.slice('WEBFLOW_PDF:'.length);
    const key = Object.keys(assetMap).find(u => decodeURIComponent(u).endsWith(name.replace(/-/g, ' ')) ||
      decodeURIComponent(u).includes(name.replace(/\.pdf$/, '')));
    if (!key) { console.error(`UNRESOLVED redirect target: ${name}`); process.exitCode = 1; continue; }
    target = assetMap[key];
  }
  if (from.includes('*') || from.includes(':')) dynamic++; else statics++;
  lines.push(`${from}  ${target}  ${status || 301}`);
}

writeFileSync('public/_redirects', lines.join('\n') + '\n');
console.log(`_redirects: ${statics} static, ${dynamic} dynamic (limits 2000 / 100)`);
if (statics > 2000 || dynamic > 100) { console.error('LIMIT EXCEEDED'); process.exitCode = 1; }
