// Emit public/_redirects for Cloudflare from BOTH sources:
//   1. reference/webflow/301-redirects.csv -- the authoritative table, exported by
//      hand from Webflow Designer (Site settings -> Publishing). Not API-accessible.
//   2. reference/redirects-discovered.tsv  -- probed from live; catches rules the
//      Designer table omits.
// Limits: 2,000 static rules, 100 dynamic.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const assetMap = JSON.parse(readFileSync('reference/asset-map.json', 'utf8'));
const byTail = new Map();
for (const [u, p] of Object.entries(assetMap)) {
  const t = decodeURIComponent(u).split('/').filter(Boolean).pop();
  if (t && !byTail.has(t)) byTail.set(t, p);
}
const WEBFLOW = /(uploads-ssl\.webflow\.com|website-files\.com|webflow-prod-assets)/;
const SITE = 'https://www.radixdlt.com';

/** Webflow-hosted targets die at cutover -- repoint them at the local mirror. */
function localise(target) {
  if (WEBFLOW.test(target)) {
    const tail = decodeURIComponent(target).split('/').filter(Boolean).pop();
    const hit = assetMap[target] ?? byTail.get(tail);
    if (hit) return { target: hit, note: null };
    return { target, note: `UNMIRRORED asset target: ${target}` };
  }
  if (target.startsWith(SITE)) return { target: target.slice(SITE.length) || '/', note: null };
  return { target, note: null };
}

const rules = new Map();   // source -> {target, status}
const notes = [];

// 1. the authoritative Designer export
if (existsSync('reference/webflow/301-redirects.csv')) {
  const lines = readFileSync('reference/webflow/301-redirects.csv', 'utf8').trim().split('\n').slice(1);
  for (const line of lines) {
    const i = line.indexOf(',');
    if (i === -1) continue;
    const source = line.slice(0, i).trim();
    const raw = line.slice(i + 1).trim();
    if (!source || !raw) continue;
    const { target, note } = localise(raw);
    if (note) notes.push(note);
    rules.set(source, { target, status: 301 });
  }
}

// 2. probed rules -- only where the Designer table has nothing
for (const raw of readFileSync('reference/redirects-discovered.tsv', 'utf8').split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const [source, status, to] = line.split('\t').map(s => s?.trim());
  if (!source || !to || rules.has(source)) continue;
  let target = to;
  if (to.startsWith('WEBFLOW_PDF:')) {
    const name = to.slice('WEBFLOW_PDF:'.length);
    const hit = [...byTail.keys()].find(t => t.replace(/[%\s]/g, '-').includes(name.replace(/\.pdf$/, '').slice(0, 20)));
    if (!hit) { notes.push(`UNRESOLVED: ${name}`); continue; }
    target = byTail.get(hit);
  }
  rules.set(source, { target, status: Number(status) || 301 });
}

const out = ['# Generated by tools/build-redirects.mjs -- do not edit by hand.',
  '# Sources: reference/webflow/301-redirects.csv (Designer export, authoritative)',
  '#          reference/redirects-discovered.tsv (probed from live)',
  ''];
let statics = 0, dynamic = 0;
for (const [source, { target, status }] of rules) {
  if (source.includes('*') || source.includes(':')) dynamic++; else statics++;
  out.push(`${source}  ${target}  ${status}`);
}
writeFileSync('public/_redirects', out.join('\n') + '\n');

console.log(`_redirects: ${rules.size} rules (${statics} static, ${dynamic} dynamic; limits 2000/100)`);
const localised = [...rules.values()].filter(r => r.target.startsWith('/assets/')).length;
console.log(`  repointed from dying Webflow CDN to local mirror: ${localised}`);
for (const n of notes) console.error(`  ! ${n}`);
if (statics > 2000 || dynamic > 100) { console.error('LIMIT EXCEEDED'); process.exitCode = 1; }
