// Phase 3: convert detail_*.html CMS templates into shells, and generate one
// [slug].astro route per collection that has a live detail route.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { documentParts } from './lib/html-slice.mjs';
import { rewriteHtml } from './lib/rewrite-urls.mjs';
import { applyShellPatch } from './lib/shell-patches.mjs';

const EXPORT = '/Volumes/Development/radix/radixdlt.com/static export';
const MARKER = '@generated by tools/convert-detail-templates.mjs';
const map = JSON.parse(readFileSync('reference/collection-map.json', 'utf8'));

// reap our own generated routes only
const reap = (dir) => {
  if (!existsSync(dir)) return;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) { reap(p); continue; }
    if (e.name.endsWith('.astro') && readFileSync(p, 'utf8').includes(MARKER)) rmSync(p);
  }
};
reap('src/pages');
rmSync('src/shells/_detail', { recursive: true, force: true });

const manifest = {};
for (const c of map) {
  if (!c.hasDetailRoute || !c.detailTemplate) continue;
  const raw = readFileSync(join(EXPORT, c.detailTemplate), 'utf8');
  const d = documentParts(raw);
  const body = applyShellPatch(c.slug, d.body);
  const dir = join('src/shells/_detail', c.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'head.html'), rewriteHtml(d.head, '', { absolutise: true }));
  writeFileSync(join(dir, 'body.html'), rewriteHtml(body, ''));
  manifest[c.slug] = { collection: c.slug, htmlAttrs: d.htmlAttrs, bodyAttrs: d.bodyAttrs, template: c.detailTemplate };

  const routeDir = join('src/pages', c.slug);
  mkdirSync(routeDir, { recursive: true });
  writeFileSync(join(routeDir, '[slug].astro'),
`---
// ${MARKER} -- edits will be lost.
import DetailPage from '@layouts/DetailPage.astro';
import { getPaths } from '../../lib/detail-data.mjs';
export const getStaticPaths = () => getPaths('${c.slug}');
const { item } = Astro.props;
---
<DetailPage collection="${c.slug}" item={item} />
`);
}
writeFileSync('src/shells/_detail/manifest.json', JSON.stringify(manifest, null, 1));
console.log(`detail templates: ${Object.keys(manifest).length} collections -> routes generated`);
for (const s of Object.keys(manifest)) console.log(`  /${s}/:slug`);
